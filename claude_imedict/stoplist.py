def canonical_ascii(word: str) -> str | None:
    """正式表記が分かっている語ならそれを返す。無ければ None。"""
    return CANONICAL_ASCII.get(word.lower())


def is_stopword(term: str) -> bool:
    if term in COMMON_JA or term in AFFIXES:
        return True
    if term.lower() in COMMON_EN:
        return True
    return False
